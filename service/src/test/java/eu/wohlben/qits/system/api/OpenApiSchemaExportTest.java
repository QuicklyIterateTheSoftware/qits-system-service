package eu.wohlben.qits.system.api;

import static io.restassured.RestAssured.given;

import eu.wohlben.qits.system.contracts.GoldenFiles;
import io.quarkus.test.junit.QuarkusTest;
import java.util.regex.Pattern;
import org.junit.jupiter.api.Test;

/**
 * Pins {@code docs/openapi.yml} to the surface this build serves at {@code /system/q/openapi}.
 * Checking the document in is what turns an API change into a reviewable diff instead of something
 * a caller discovers at runtime. Copied from qits-projects-service's, which set the shape.
 *
 * <p><b>It compares by default</b> and fails with a unified diff when the served document moved;
 * {@code -Dgolden.update=true} (or {@code QITS_GOLDEN_UPDATE=true}) rewrites the file instead — the
 * switch every golden here shares ({@link GoldenFiles}). It is a test only because {@code
 * @QuarkusTest} is the cheapest way to stand the application up and read its own document.
 *
 * <p>{@code info.version} is the release version and is left out of the comparison: every release
 * bumps the pom, so comparing it would fail every release request's gate on a line no API change
 * moved. A rewrite still writes the version it served.
 *
 * <p>{@code openIdConnectUrl} is left out too, for a different reason: it is {@code
 * quarkus.oidc.auth-server-url}, which names the environment's own idp ({@code
 * http://${QITS_ENVIRONMENT:dev}-qits-idp:8080/idp}), so a runner with {@code QITS_ENVIRONMENT} set
 * would serve another line than a clone without it. It is configuration, not the API; a rewrite
 * writes whatever the run served.
 *
 * <p>The test classpath is indexed too, so any {@code @Path} resource under {@code src/test} of a
 * module on this classpath would land in the committed document unless it is {@code
 * @Operation(hidden = true)}. There is none today: the suite's far sides ({@code IdpStub}, the fake
 * docker, {@code FakeTargetRunner}) are a JDK server, a script and a socket client, not resources.
 */
@QuarkusTest
public class OpenApiSchemaExportTest {

  /** The one two-space-indented {@code version:} key in the document is {@code info.version}. */
  private static final Pattern INFO_VERSION = Pattern.compile("(?m)^  version: .*$");

  /** The security scheme's discovery url: the environment's idp, see the class comment. */
  private static final Pattern OPEN_ID_CONNECT_URL =
      Pattern.compile("(?m)^(\\s+openIdConnectUrl: ).*$");

  @Test
  public void exportOpenApiSchema() {
    String schema =
        given().when().get("/system/q/openapi").then().statusCode(200).extract().asString();

    String header =
        "# THIS FILE IS GENERATED BY OpenApiSchemaExportTest — DO NOT EDIT MANUALLY.\n"
            + "# Run `./mvnw -pl service -am test -Dtest=OpenApiSchemaExportTest"
            + " -Dsurefire.failIfNoSpecifiedTests=false -Dquarkus.http.test-port=0"
            + " -Dgolden.update=true` to regenerate.\n";

    GoldenFiles.compareOrWrite(
        GoldenFiles.repositoryRoot().resolve("docs").resolve("openapi.yml"),
        header + schema,
        text ->
            OPEN_ID_CONNECT_URL
                .matcher(INFO_VERSION.matcher(text).replaceAll("  version: <release version>"))
                .replaceAll("$1<the environment's idp>"));
  }
}
